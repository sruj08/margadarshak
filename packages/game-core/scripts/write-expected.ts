// Writes src/fixtures/expected.ts from the current scorers. Run only when adding vectors or after a
// reviewed scoring-major bump; review the diff by hand (golden vectors are append-only).
//   node --experimental-strip-types scripts/write-expected.ts && biome format --write src/fixtures/expected.ts
// `replay.inputs` is stored empty: it always equals the vector's replayPackage.inputs (pinned by the
// digest test), so storing it again would only bloat the file.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { allVectorInputs } from "../src/fixtures/vectors.ts";
import { replay } from "../src/scoring/index.ts";

const out: Record<string, unknown> = {};
for (const v of allVectorInputs()) {
  const r = replay(v.manifest, v.ctx, v.replayPackage, v.content);
  out[v.name] = { ...r, replay: { seed: r.replay.seed, inputs: "" } };
}
const header = `// GENERATED by scripts/write-expected.ts from reviewed scorer output. Append-only: changing an
// expected result requires a scoring-major bump and a CHANGELOG line (GAME_SDK §9).
import type { SessionResult } from "../schema/result.ts";

/** Expected results by vector name; \`replay.inputs\` is filled from the vector's package. */
export const EXPECTED_RESULTS: Readonly<Record<string, SessionResult>> = `;
const file = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "fixtures", "expected.ts");
writeFileSync(file, `${header}${JSON.stringify(out, null, 2)};\n`);
process.stdout.write(`wrote ${Object.keys(out).length} expected results to ${file}\n`);
