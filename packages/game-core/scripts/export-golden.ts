// Exports every golden vector as a language-neutral contract file, fixtures/golden.json:
//   node --experimental-strip-types scripts/export-golden.ts   (= pnpm fixtures:golden)
//   then: node ../../node_modules/@biomejs/biome/bin/biome format --write packages/game-core/fixtures/golden.json
//
// Each vector carries the exact score-verifier POST /verify request body, the expected server
// result and its digest. Consumers:
//   - the Go contract test (services/api internal/adapters/compute/contract_test.go) signs and posts
//     every `request` to a verifier started without VERIFIER_CONTENT_DIR (built-in fixture content)
//     and compares `result` and `digest`;
//   - the verifier CLI: `node dist/cli/replay.js packages/game-core/fixtures/golden.json`.
// Nazar requests send their clip documents inline (`content.items`), as the Go API does; the other
// games rely on the verifier's content store. A drift test (test/golden-export.test.ts) fails when
// this file no longer matches the vectors.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fixtureContentDocs, type GoldenVector, goldenVectors } from "../src/fixtures/index.ts";
import { GAME_CORE_VERSION } from "../src/index.ts";
import { SCORING_VERSIONS } from "../src/scoring/index.ts";
import { canonicalDigest } from "../src/sdk/index.ts";

export const GOLDEN_SCHEMA = "margdarshak.game-core.golden/1";
export const GOLDEN_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "fixtures",
  "golden.json",
);

/** The score-verifier /verify body for a vector (flat ARCHITECTURE §6 shape, GAME_SDK §6.3). */
export function verifyRequest(v: GoldenVector, docs: Record<string, unknown>) {
  return {
    sid: v.ctx.sid,
    gameId: v.ctx.gameId,
    gameVersion: v.manifest.version,
    scoringVersion: v.manifest.scoringVersion,
    mode: v.ctx.mode,
    difficulty: v.ctx.difficulty,
    seed: v.ctx.seed,
    seedOrigin: v.ctx.seedOrigin,
    items: v.ctx.items,
    tenant: v.ctx.tenant,
    rulePackVersion: v.ctx.rulePackVersion,
    telemetryVersion: v.replayPackage.telemetryVersion,
    encoding: v.replayPackage.encoding,
    inputs: v.replayPackage.inputs,
    digest: v.replayPackage.digest,
    eventCount: v.replayPackage.eventCount,
    context: {
      userBand: v.ctx.userBand,
      locale: v.ctx.locale,
      a11yModes: v.ctx.a11y.modes,
      deviceClass: v.ctx.deviceClass,
      offline: v.ctx.offline,
      serverStartIso: v.ctx.serverStartIso,
    },
    ...(v.ctx.gameId === "nazar"
      ? { content: { items: v.ctx.items.map((it) => docs[it.ref]) } }
      : {}),
  };
}

export function goldenExport() {
  const docs = fixtureContentDocs();
  const vectors = goldenVectors().map((v) => ({
    name: v.name,
    description: v.description,
    tags: [...v.tags],
    gameId: v.ctx.gameId,
    request: verifyRequest(v, docs),
    expected: {
      // replay.inputs always equals request.inputs; stored empty to keep the file small.
      result: { ...v.expectedResult, replay: { seed: v.expectedResult.replay.seed, inputs: "" } },
      digest: canonicalDigest(v.expectedResult),
      eventsDigest: v.replayPackage.digest,
    },
  }));
  return {
    schema: GOLDEN_SCHEMA,
    gameCoreVersion: GAME_CORE_VERSION,
    scoringVersions: SCORING_VERSIONS,
    notes: [
      "Generated by packages/game-core scripts/export-golden.ts from src/fixtures; do not edit by hand.",
      "POST each `request` to the score verifier's /verify (Margdarshak-Signature over the exact body bytes) with its built-in fixture content (no VERIFIER_CONTENT_DIR): expect 200, `result` deep-equal to expected.result and `digest` equal to expected.digest.",
      'expected.result.replay.inputs is stored as "": set it to request.inputs before comparing (it always equals them). `digest` is sha256 over the canonical (sorted-key) JSON of the full result, inputs included; `eventsDigest` echoes the request digest.',
    ],
    count: vectors.length,
    vectors,
  };
}

function main(): void {
  const out = goldenExport();
  writeFileSync(GOLDEN_PATH, `${JSON.stringify(out, null, 2)}\n`, "utf8");
  process.stdout.write(`wrote ${out.count} golden vectors to ${GOLDEN_PATH}\n`);
}

if (process.argv[1] !== undefined && join(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
