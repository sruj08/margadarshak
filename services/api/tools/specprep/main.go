// Command specprep down-converts api/openapi.yaml (OpenAPI 3.1) into an OpenAPI 3.0-shaped
// JSON document that oapi-codegen (kin-openapi, 3.0 only) can read. It is a build-time helper
// for `go generate ./internal/httpapi/gen`; the 3.1 YAML stays the source of truth (MD-055).
//
// Conversions (schema objects only, applied recursively):
//   - type: [X, "null"]  -> type: X, nullable: true
//   - type: [A, B, ...]  -> no type (any value)
//   - const: v           -> enum: [v]
//   - examples: [...]    -> example: first item
//   - numeric exclusiveMinimum/Maximum -> minimum/maximum + boolean flag
//   - contentMediaType, $schema, jsonSchemaDialect are dropped
//
// Usage: go run ./tools/specprep <in.yaml> <out.json>
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: specprep <in.yaml> <out30.json> <operations.gen.go>")
		os.Exit(2)
	}
	in, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(in, &doc); err != nil {
		fail(fmt.Errorf("parse %s: %w", os.Args[1], err))
	}
	// The operation table is read from the untouched 3.1 document.
	ops := Operations(doc)
	if err := os.WriteFile(os.Args[3], []byte(ops), 0o644); err != nil {
		fail(err)
	}
	out := Convert(doc)
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], b, 0o644); err != nil {
		fail(err)
	}
}

// Operations renders a Go table of every operation: method, path, operationId, x-api-id and
// the security requirements (OR of AND-sets). The HTTP layer enforces auth from this table,
// so the spec, not hand-written code, decides who may call what.
func Operations(doc map[string]any) string {
	var globalSec []any
	if s, ok := doc["security"].([]any); ok {
		globalSec = s
	}
	paths, _ := doc["paths"].(map[string]any)
	pathKeys := make([]string, 0, len(paths))
	for p := range paths {
		pathKeys = append(pathKeys, p)
	}
	sort.Strings(pathKeys)
	var sb strings.Builder
	sb.WriteString("// Code generated by tools/specprep from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n\n")
	sb.WriteString("// Operations maps \"METHOD /path/{param}\" to the operation's contract metadata.\n")
	sb.WriteString("var Operations = map[string]Operation{\n")
	for _, p := range pathKeys {
		item, _ := paths[p].(map[string]any)
		for _, method := range []string{"get", "put", "post", "delete", "patch", "head", "options"} {
			op, ok := item[method].(map[string]any)
			if !ok {
				continue
			}
			sec := globalSec
			if s, ok := op["security"].([]any); ok {
				sec = s
			}
			id, _ := op["operationId"].(string)
			apiID, _ := op["x-api-id"].(string)
			proposed, _ := op["x-proposed"].(bool)
			fmt.Fprintf(&sb, "\t%q: {Method: %q, Path: %q, OperationID: %q, APIID: %q, Proposed: %t, Security: %s},\n",
				strings.ToUpper(method)+" "+p, strings.ToUpper(method), p, id, apiID, proposed, renderSecurity(sec))
		}
	}
	sb.WriteString("}\n")
	return sb.String()
}

func renderSecurity(sec []any) string {
	var sb strings.Builder
	sb.WriteString("[]SecurityRequirement{")
	for i, req := range sec {
		if i > 0 {
			sb.WriteString(", ")
		}
		m, _ := req.(map[string]any)
		names := make([]string, 0, len(m))
		for k := range m {
			names = append(names, k)
		}
		sort.Strings(names)
		sb.WriteString("{")
		for j, name := range names {
			if j > 0 {
				sb.WriteString(", ")
			}
			var scopes []string
			if arr, ok := m[name].([]any); ok {
				for _, s := range arr {
					scopes = append(scopes, fmt.Sprint(s))
				}
			}
			fmt.Fprintf(&sb, "{Scheme: %q, Scopes: %#v}", name, scopes)
		}
		sb.WriteString("}")
	}
	sb.WriteString("}")
	return sb.String()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "specprep:", err)
	os.Exit(1)
}

// Convert returns a 3.0-shaped copy of an OpenAPI 3.1 document.
func Convert(doc map[string]any) map[string]any {
	doc["openapi"] = "3.0.3"
	delete(doc, "jsonSchemaDialect")
	delete(doc, "webhooks")
	if info, ok := doc["info"].(map[string]any); ok {
		delete(info, "summary")
		if lic, ok := info["license"].(map[string]any); ok {
			delete(lic, "identifier")
		}
	}
	out := walk(doc).(map[string]any)
	inlineDeepRefs(out, out)
	return out
}

// inlineDeepRefs replaces $refs that point inside a schema (for example
// #/components/schemas/SessionResult/properties/integrity) with a copy of the target,
// because oapi-codegen only resolves refs to whole components.
func inlineDeepRefs(root map[string]any, v any) {
	switch t := v.(type) {
	case map[string]any:
		if ref, ok := t["$ref"].(string); ok && strings.Count(ref, "/") > 3 {
			if target, ok := lookup(root, ref); ok {
				delete(t, "$ref")
				for k, val := range deepCopy(target).(map[string]any) {
					t[k] = val
				}
			}
		}
		for _, child := range t {
			inlineDeepRefs(root, child)
		}
	case []any:
		for _, child := range t {
			inlineDeepRefs(root, child)
		}
	}
}

func lookup(root map[string]any, ref string) (any, bool) {
	var cur any = root
	for _, part := range strings.Split(strings.TrimPrefix(ref, "#/"), "/") {
		m, ok := cur.(map[string]any)
		if !ok {
			return nil, false
		}
		part = strings.ReplaceAll(strings.ReplaceAll(part, "~1", "/"), "~0", "~")
		if cur, ok = m[part]; !ok {
			return nil, false
		}
	}
	_, isMap := cur.(map[string]any)
	return cur, isMap
}

func deepCopy(v any) any {
	switch t := v.(type) {
	case map[string]any:
		c := make(map[string]any, len(t))
		for k, val := range t {
			c[k] = deepCopy(val)
		}
		return c
	case []any:
		c := make([]any, len(t))
		for i, val := range t {
			c[i] = deepCopy(val)
		}
		return c
	default:
		return v
	}
}

func walk(v any) any {
	switch t := v.(type) {
	case map[string]any:
		fixSchema(t)
		for k, child := range t {
			t[k] = walk(child)
		}
		return t
	case []any:
		for i := range t {
			t[i] = walk(t[i])
		}
		return t
	default:
		return v
	}
}

// fixSchema rewrites 3.1-only keywords in place. It is harmless on non-schema maps because
// the keywords it touches only have these meanings inside schema objects.
func fixSchema(m map[string]any) {
	if types, ok := m["type"].([]any); ok {
		var nonNull []any
		hasNull := false
		for _, x := range types {
			if s, _ := x.(string); s == "null" {
				hasNull = true
				continue
			}
			nonNull = append(nonNull, x)
		}
		if len(nonNull) == 1 {
			m["type"] = nonNull[0]
		} else {
			delete(m, "type")
		}
		if hasNull {
			m["nullable"] = true
		}
	}
	if c, ok := m["const"]; ok {
		m["enum"] = []any{c}
		delete(m, "const")
	}
	if ex, ok := m["examples"].([]any); ok {
		if len(ex) > 0 {
			m["example"] = ex[0]
		}
		delete(m, "examples")
	}
	for _, kw := range []string{"exclusiveMinimum", "exclusiveMaximum"} {
		var n any
		switch x := m[kw].(type) {
		case int, float64:
			n = x
		default:
			continue
		}
		if kw == "exclusiveMinimum" {
			m["minimum"] = n
		} else {
			m["maximum"] = n
		}
		m[kw] = true
	}
	delete(m, "contentMediaType")
	delete(m, "$schema")
}
