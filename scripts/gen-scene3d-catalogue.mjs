// Derives the 3D scene catalogue from content/nazar/scenes.json (the scene spec). Run: node scripts/gen-scene3d-catalogue.mjs
// Nominal onset = start of the hazardBegins shot + its cueAtS; raters confirm it (NAZAR §17).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

const WINDOW_MS = 4500;
const src = JSON.parse(readFileSync(`${root}content/nazar/scenes.json`, "utf8"));
export const SCENES_JSON = src;
export function derive(s) {
  let t = 0;
  let onset = null;
  for (const sh of s.shots) {
    if (sh.hazardBegins) onset = Math.round((t + (sh.cueAtS ?? 0)) * 1000);
    t += sh.durationS;
  }
  const durationMs = Math.round(t * 1000);
  const aMs = onset;
  const bMs = onset === null ? null : Math.min(durationMs - 1000, onset + WINDOW_MS);
  return {
    id: s.sceneId,
    hazardType: s.hazardType,
    pov: s.pov,
    setting: s.setting,
    roadType: s.roadType,
    timeOfDay: s.timeOfDay,
    weather: s.weather,
    speedKmh: s.speedKmh,
    durationMs,
    aMs,
    bMs,
    difficulty: s.difficulty,
    occlusion: s.occlusion,
    cue: s.cue,
  };
}
if (process.argv[1]?.endsWith("gen-scene3d-catalogue.mjs")) {
  const rows = src.scenes.map(derive);
  writeFileSync(
    `${root}apps/web/src/features/nazar/scene3d/catalogue.data.ts`,
    `// GENERATED by scripts/gen-scene3d-catalogue.mjs from content/nazar/scenes.json. Do not edit.\nimport type { SceneRow } from "./types";\n\nexport const SCENES: readonly SceneRow[] = ${JSON.stringify(rows, null, 2)};\n`,
  );
  process.stdout.write(`${rows.length} scenes
`);
}
